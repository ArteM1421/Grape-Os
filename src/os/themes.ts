export function applyTheme(theme: PyOSTheme): void {
  const root = document.documentElement;
  root.style.setProperty('--pyos-bg', theme.bg);
  root.style.setProperty('--pyos-bg-deep', theme.bgDeep);
  root.style.setProperty('--pyos-accent', theme.accent);
  root.style.setProperty('--pyos-accent-2', theme.accent2);
  root.style.setProperty('--pyos-accent-3', theme.accent3);
  root.style.setProperty('--pyos-glass', theme.glass);
  root.style.setProperty('--pyos-glass-border', theme.glassBorder);
  root.style.setProperty('--pyos-glass-hover', theme.glassHover);
  root.style.setProperty('--pyos-text', theme.text);
  root.style.setProperty('--pyos-text-dim', theme.textDim);
  root.style.setProperty('--pyos-text-bright', theme.textBright);
  root.style.setProperty('--pyos-radius', `${theme.radius}px`);
  root.style.setProperty('--pyos-radius-sm', `${theme.radiusSm}px`);
  root.style.setProperty('--pyos-radius-lg', `${theme.radiusLg}px`);
  root.style.setProperty('--pyos-shadow-color', theme.shadowColor);
  root.style.setProperty('--pyos-glow-color', theme.glowColor);
  root.style.setProperty('--pyos-success', theme.successColor);
  root.style.setProperty('--pyos-warning', theme.warningColor);
  root.style.setProperty('--pyos-error', theme.errorColor);
  root.style.setProperty('--pyos-link', theme.linkColor);
  root.style.setProperty('--pyos-selection-bg', theme.selectionBg);
  root.style.setProperty('--pyos-selection-text', theme.selectionText);
  root.style.setProperty('--pyos-font', theme.font);
  root.style.setProperty('--pyos-mono-font', theme.monoFont);
  root.style.setProperty('--pyos-titlebar-bg', theme.titlebarBg);
  root.style.setProperty('--pyos-dock-bg', theme.dockBg);
  root.style.setProperty('--pyos-scrollbar-thumb', theme.scrollbarThumb);
  root.style.setProperty('--pyos-scrollbar-thumb-hover', theme.scrollbarThumbHover);
  root.style.setProperty('--pyos-wallpaper', theme.wallpaper);
  root.style.setProperty('--pyos-wallpaper-overlay', theme.wallpaperOverlay);
}

export function getTheme(id: string): PyOSTheme {
  return THEMES.find((t) => t.id === id) ?? THEMES[0];
}
